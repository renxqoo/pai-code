/**
 * 整行 shell 注释谓词（单一真相）：命令文本按行拆开后，`#` / `;` 起头（允许行首
 * 空白）的行是注释——展示层整行剥掉、数据层截断时不占预算，两侧必须同一判定，
 * 否则截断吃掉的与展示剥掉的各行其是，命令本体可能两头落空。
 *
 * 只认整行：行内注释（`ls # x`）折平后无法与「参数里带 #」区分，一律保留
 * （保守：宁可多显示，不可吃掉命令片段）。
 */

/** 该行是否为整行 shell 注释（`#` / `;` 起头，行首空白容忍）。 */
export function isCommentLine(line: string): boolean {
  return /^\s*[#;]/.test(line);
}
